def write_qa(checklist_result: dict | None = None) -> int:
    metrics = calculate_metrics()
    lines = ["# 导师问答手册", "", "> 使用说明：每题先用“30 秒回答”，被追问时再展开。所有结论均为案例计划阶段判断。", "", f"> 关键记忆数字：2022 年收入增速 {metrics['revenue_growth_2022']:.2%}；应收/收入 {metrics['receivables_to_revenue_2022']:.2%}；流动比率 {metrics['current_ratio_2022']:.2f}；资产负债率 {metrics['debt_ratio_2022']:.2%}。", ""]
    questions = _questions(checklist_result)
    page_indexes = [6, 6, 6, 6, 7, 7, 7, 8, 8, 8, 9, 9, 9, 5, 5, 4, 5, 12, 5, 10, 10, 13, 13, 13, 11, 11, 13, 11, 6, 12, 14, 15]
    if len(questions) != len(page_indexes):
        raise AssertionError(f"QA page map mismatch: {len(questions)} questions vs {len(page_indexes)} pages")
    for index, ((question, short, expanded), page) in enumerate(zip(questions, page_indexes), start=1):
        lines.extend([f"## {index}. {question}（对应 PDF 第 {page} 页）", "", f"**30 秒回答：** {short}", "", f"**追问展开：** {expanded}", ""])
    lines.extend(["## 最后提醒", "", "- 始终区分：案例事实、自动计算、审计推测、审计结论。", "- 避免说“已经造假/已经错报”，应说“存在风险，需要通过程序验证”。", "- 遇到案例未提供的信息，直接说明限制和正式审计中应补充的证据。", ""])
    (OUTPUT_DIR / QA_OUTPUT_NAME).write_text("\n".join(lines), encoding="utf-8")
    return len(questions)
